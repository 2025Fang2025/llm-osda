"""Step 01: Generate rich, diverse, internally-consistent user profiles via LLM.

Each profile is generated by giving the LLM a few seed attributes (age + gender)
and asking it to produce a complete, self-consistent persona.

Usage:
    cd data_pipeline
    python scripts/01_make_profiles.py [--dry-run] [--limit N]
"""

import json
import random
import argparse
import asyncio
import re
from pathlib import Path
from typing import List, Dict, Any

from utils_io import write_jsonl
from _llm import call_llm_async, CFG


# ── Seed pools (only age & gender are sampled; everything else is LLM-generated) ──

AGES = ["18-22", "23-27", "28-34", "35-44", "45-54", "55+"]

GENDERS = ["female", "male", "non-binary"]

# Category pool provided to LLM as reference (it picks 2-4)
CATEGORY_POOL = [
    "electronics", "beauty", "home", "sports", "fashion",
    "kitchen", "health", "books", "toys", "pet supplies",
    "outdoor", "office supplies",
]

# Variation hints to prevent duplicate profiles when seeds are the same
VARIATION_HINTS = [
    "tech-savvy and loves gadgets",
    "outdoorsy and active lifestyle",
    "homebody who loves cooking",
    "fashion-forward and trend-conscious",
    "health-conscious and into wellness",
    "creative and artsy",
    "practical minimalist",
    "social butterfly who loves hosting",
    "bookworm and lifelong learner",
    "pet parent",
    "fitness enthusiast",
    "budget hacker who maximizes every dollar",
    "eco-conscious and sustainability-focused",
    "new to online shopping",
    "impulse buyer attracted to novelty",
    "gift shopper who often buys for others",
    "DIY enthusiast",
    "busy professional with no time to browse",
    "vintage and thrift lover",
    "gamer and digital entertainment fan",
]


# ── Prompt template ──

PROFILE_GENERATION_PROMPT = """You are a user persona generator for an e-commerce AI assistant research project.

Given the seed attributes below, generate a COMPLETE and INTERNALLY CONSISTENT user profile. Every field must logically fit together — no contradictions.

## Seed Attributes
- Age: {age}
- Gender: {gender}
- Personality direction: {variation_hint}

## Required Output Fields
Generate a JSON object with exactly these fields:
{{
  "occupation": "<realistic job/role that fits the age>",
  "budget": "<one of: very low (student budget), low, medium, high, luxury>",
  "personality": "<one shopping personality trait, incorporating the personality direction above>",
  "life_situation": "<current life context that fits age/occupation, be specific and unique>",
  "shopping_habit": "<one shopping behavior pattern>",
  "preferred_categories": ["<2-4 categories from: {category_pool}>"],
  "pain_point": "<one shopping pain point that fits the persona>"
}}

## Consistency Rules
- A college student should be 18-27, not 55+
- A retired person should be 55+, not 18-22
- Budget should match occupation (students = low/very low, engineers = medium/high, etc.)
- Life situation should be plausible for the age and occupation
- Shopping habit should not contradict personality (e.g. "cautious researcher" should not "prefer quick decisions")
- Pain points should relate to the persona's actual situation
- Make this persona DISTINCT — avoid generic descriptions

## Output
Return ONLY the JSON object. No markdown, no explanation, no extra text."""


def parse_profile_json(text: str) -> dict:
    """Parse LLM output into a profile dict. Handles markdown wrapping."""
    text = text.strip()

    # Strip ```json ... ``` wrapper
    json_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if json_match:
        text = json_match.group(1)

    # Try direct parse
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # Fallback: find first { ... }
    brace_match = re.search(r"\{.*\}", text, re.DOTALL)
    if brace_match:
        try:
            return json.loads(brace_match.group(0))
        except json.JSONDecodeError:
            pass

    return None


def validate_profile(profile: dict) -> bool:
    """Basic validation: all required fields present and non-empty."""
    required = [
        "occupation", "budget", "personality",
        "life_situation", "shopping_habit",
        "preferred_categories", "pain_point",
    ]
    for key in required:
        if key not in profile or not profile[key]:
            return False
    if not isinstance(profile["preferred_categories"], list):
        return False
    if len(profile["preferred_categories"]) < 2:
        return False
    return True


def build_profile_tags(age: str, gender: str, profile: dict) -> str:
    """Build the natural language profile description for LLM prompts."""
    cats = ", ".join(profile["preferred_categories"])
    return (
        "Age: {age}; Gender: {gender}; Occupation: {occupation}; "
        "Budget level: {budget}; "
        "Personality: {personality}; "
        "Current situation: {life_situation}; "
        "Shopping habit: {shopping_habit}; "
        "Preferred categories: {cats}; "
        "Pain point: {pain_point}."
    ).format(
        age=age, gender=gender, cats=cats, **profile,
    )


async def generate_one_profile(age: str, gender: str, variation_hint: str, profile_id: str) -> dict:
    """Generate a single profile via LLM."""
    prompt = PROFILE_GENERATION_PROMPT.format(
        age=age,
        gender=gender,
        variation_hint=variation_hint,
        category_pool=", ".join(CATEGORY_POOL),
    )
    messages = [{"role": "user", "content": prompt}]

    text = await call_llm_async(
        messages,
        model_key="dialogue_user",
        temperature=0.9,
        max_tokens=500,
    )

    profile = parse_profile_json(text)
    if profile is None or not validate_profile(profile):
        print(f"  [warn] {profile_id}: failed to parse/validate, retrying...")
        # One retry with higher temperature
        text = await call_llm_async(
            messages,
            model_key="dialogue_user",
            temperature=1.0,
            max_tokens=500,
        )
        profile = parse_profile_json(text)
        if profile is None or not validate_profile(profile):
            print(f"  [error] {profile_id}: giving up after retry. Raw: {text[:200]}")
            return None

    tags = {
        "age": age,
        "gender": gender,
        "occupation": profile["occupation"],
        "budget": profile["budget"],
        "personality": profile["personality"],
        "life_situation": profile["life_situation"],
        "shopping_habit": profile["shopping_habit"],
        "preferred_categories": profile["preferred_categories"],
        "pain_point": profile["pain_point"],
    }

    return {
        "profile_id": profile_id,
        "tags": tags,
        "profile_tags": build_profile_tags(age, gender, profile),
    }


async def main():
    parser = argparse.ArgumentParser(description="Generate user profiles via LLM")
    parser.add_argument("--dry-run", action="store_true",
                        help="Show sample prompt without calling LLM")
    parser.add_argument("--limit", type=int, default=0,
                        help="Only generate N profiles (0 = all)")
    args = parser.parse_args()

    n_profiles = int(CFG["project"]["n_profiles"])
    seed = int(CFG["project"]["seed"])
    rng = random.Random(seed)

    if args.limit > 0:
        n_profiles = min(args.limit, n_profiles)

    # Pre-sample seed attributes for all profiles
    seeds = []
    for i in range(n_profiles):
        age = rng.choice(AGES)
        gender = rng.choice(GENDERS)
        variation_hint = rng.choice(VARIATION_HINTS)
        profile_id = "h_{:04d}".format(i)
        seeds.append((age, gender, variation_hint, profile_id))

    print(f"Generating {n_profiles} profiles (seed={seed})...")

    if args.dry_run:
        age, gender, variation_hint, pid = seeds[0]
        print(f"\n[dry-run] Sample seed: {pid} age={age} gender={gender} hint={variation_hint}")
        print(f"\n[dry-run] Sample prompt:\n")
        print(PROFILE_GENERATION_PROMPT.format(
            age=age, gender=gender,
            variation_hint=variation_hint,
            category_pool=", ".join(CATEGORY_POOL),
        )[:800])
        print("...")
        return

    # Batch generation with concurrency control
    batch_size = CFG["rate_limit"]["max_concurrency"]
    checkpoint_every = 1000  # 每生成 1000 个保存一次
    all_profiles = []
    out_path = Path(__file__).resolve().parents[1] / "data" / "profiles_.jsonl"

    # 如果已有 checkpoint 文件，加载已完成的部分，跳过已生成的
    if out_path.exists():
        from utils_io import read_jsonl
        existing = list(read_jsonl(out_path))
        if existing:
            all_profiles = existing
            print(f"  Loaded {len(existing)} existing profiles from checkpoint, resuming...")

    # 计算从哪里继续
    done_ids = {p["profile_id"] for p in all_profiles}
    remaining_seeds = [(a, g, h, pid) for a, g, h, pid in seeds if pid not in done_ids]
    print(f"  {len(done_ids)} already done, {len(remaining_seeds)} remaining")

    for i in range(0, len(remaining_seeds), batch_size):
        batch = remaining_seeds[i:i + batch_size]
        coros = [
            generate_one_profile(age, gender, hint, pid)
            for age, gender, hint, pid in batch
        ]
        results = await asyncio.gather(*coros, return_exceptions=True)

        for r in results:
            if isinstance(r, Exception):
                print(f"  [error] {r}")
            elif r is not None:
                all_profiles.append(r)

        done = len(done_ids) + min(i + batch_size, len(remaining_seeds))
        print(f"  progress: {done}/{len(seeds)} ({len(all_profiles)} valid)")

        # 每 checkpoint_every 个保存一次
        if len(all_profiles) % checkpoint_every < batch_size and len(all_profiles) >= checkpoint_every:
            write_jsonl(out_path, all_profiles)
            print(f"  ** checkpoint saved: {len(all_profiles)} profiles -> {out_path}")

    # Final save
    write_jsonl(out_path, all_profiles)
    print(f"\nWrote {len(all_profiles)} profiles -> {out_path}")

    # Show samples
    print("\nSample profiles:")
    for r in all_profiles[:3]:
        print(f"  [{r['profile_id']}] {r['profile_tags'][:120]} ...")


if __name__ == "__main__":
    asyncio.run(main())
